#!/usr/bin/env bash
# Regenerate PROGRESS.md: every <topic>/<problem>/ folder holding a .java file,
# grouped by topic. The date and approach come from the commit that first added
# the folder ("... using <approach> approach"); uncommitted folders show "—".
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

# One history pass, oldest first: "<topic>/<problem>|<date>|<subject>" per added file.
added() {
  git log --reverse --no-renames --diff-filter=A --name-only --date=short --format='@%ad|%s' |
  awk -F '/' '/^@/ { c = substr($0, 2); next } NF >= 3 { print $1 "/" $2 "|" c }'
}

rows=$(
  find . -mindepth 3 -maxdepth 3 -name '*.java' -not -path './.*' |
    sed -E 's#^\./([^/]+/[^/]+)/.*#\1#' | sort -u |
    awk '
      NR == FNR {
        p = index($0, "|"); d = substr($0, 1, p - 1)
        if (!(d in first)) first[d] = substr($0, p + 1)
        next
      }
      {
        split($0, part, "/"); topic = part[1]; name = part[2]
        num = ""
        if (match(name, /^[0-9]+-/)) {
          slug = substr(name, RLENGTH + 1)
          # Blind75 prefixes are list positions, not LeetCode numbers.
          if (topic != "Blind75") num = substr(name, 1, RLENGTH - 1)
        } else slug = name
        nw = split(slug, w, "-"); title = ""
        for (i = 1; i <= nw; i++) {
          t = toupper(substr(w[i], 1, 1)) substr(w[i], 2)
          if (tolower(t) ~ /^(ii|iii|iv)$/) t = toupper(t)
          title = title (i > 1 ? " " : "") t
        }
        date = "—"; approach = ""
        if ($0 in first) {
          c = first[$0]; p = index(c, "|")
          date = substr(c, 1, p - 1); subject = substr(c, p + 1)
          if (match(subject, / using /)) {
            approach = substr(subject, RSTART + RLENGTH)
            sub(/ approach$/, "", approach)
          }
        }
        printf "%s|%s|%s|%s|%s|%s\n", topic, (num == "" ? 999999 : num), title, date, approach, $0
      }' <(added) - |
    sort -t '|' -k1,1f -k2,2n -k3,3
)

total=$(printf '%s\n' "$rows" | grep -c .)

{
  echo "# Progress"
  echo
  echo "_Generated by \`ci/progress.sh\` — don't edit by hand._"
  echo
  echo "**$total problems.** $(printf '%s\n' "$rows" | cut -d '|' -f1 | uniq -c |
    awk '{ printf "%s%s %s", (NR > 1 ? " · " : ""), $2, $1 }')"
  printf '%s\n' "$rows" | awk -F '|' '
    $1 != topic {
      topic = $1
      printf "\n## %s\n\n| # | Problem | Approach | Added |\n|---|---------|----------|-------|\n", topic
    }
    { printf "| %s | [%s](%s) | %s | %s |\n", ($2 == 999999 ? "" : $2), $3, $6, $5, $4 }
  '
} > PROGRESS.md

echo "Wrote PROGRESS.md ($total problems)"
